def set_cell_border(cell, **kwargs):
    """Set cell borders with single black lines by default."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = tcPr.first_child_found_in("w:tcBorders")
    if tcBorders is None:
        tcBorders = OxmlElement('w:tcBorders')
        tcPr.append(tcBorders)
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        edge_data = kwargs.get(edge)
        if edge_data:
            tag = 'w:{}'.format(edge)
            element = tcBorders.find(qn(tag))
            if element is None:
                element = OxmlElement(tag)
                tcBorders.append(element)
            for key, val in edge_data.items():
                element.set(qn('w:{}'.format(key)), str(val))

def set_cell_margins(cell, top=100, bottom=100, left=140, right=140):
    """Set inner cell margins in dxa (1 pt = 20 dxa)."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for m, val in [('top', top), ('bottom', bottom), ('left', left), ('right', right)]:
        node = OxmlElement(f'w:{m}')
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)

def set_cell_shading(cell, color_hex="F2F2F2"):
    """Set background fill color."""
    tcPr = cell._tc.get_or_add_tcPr()
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{color_hex}"/>')
    tcPr.append(shd)

def set_cell_content(cell, text, font_name="Times New Roman", font_size=Pt(10),
                     bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.LEFT,
                     color=None, border=True, shading=None):
    """Clean cell and add formatted paragraph."""
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = 1.0
    
    run = p.add_run(str(text))
    run.font.name = font_name
    run.font.size = font_size
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    if border:
        set_cell_border(
            cell,
            top=dict(val='single', sz='4', color='000000'),
            bottom=dict(val='single', sz='4', color='000000'),
            left=dict(val='single', sz='4', color='000000'),
            right=dict(val='single', sz='4', color='000000')
        )
    set_cell_margins(cell)
    if shading:
        set_cell_shading(cell, shading)

def format_paragraph(p, font_name="Times New Roman", font_size=Pt(12),
                     bold=False, italic=False, space_before=Pt(0),
                     space_after=Pt(4), line_spacing=1.15,
                     align=WD_ALIGN_PARAGRAPH.LEFT):
    p.alignment = align
    p.paragraph_format.space_before = space_before
    p.paragraph_format.space_after = space_after
    p.paragraph_format.line_spacing = line_spacing
    for r in p.runs:
        r.font.name = font_name
        r.font.size = font_size
        if bold:
            r.bold = True
        if italic:
            r.italic = True

